/**
 * 某学科的模块列表（可按年级筛选，'all' 专题始终包含）。
 * @param {string} subject 学科键。
 * @param {string|null} [grade] 年级键；null 表示全部。
 * @returns {object[]} 模块列表。
 */
export function syllabusFor(subject, grade = null) {
  const modules = SYLLABUS[subject] ?? []
  if (grade === null) return modules
  return modules.filter((m) => m.grade === grade || m.grade === 'all')
}

/**
 * 某学科的全部章节名（拍平，便于做候选下拉与模糊匹配）。
 * @param {string} subject 学科键。
 * @param {string|null} [grade] 年级键。
 * @returns {string[]} 章节名数组。
 */
export function chaptersOf(subject, grade = null) {
  return syllabusFor(subject, grade).flatMap((m) => m.chapters)
}

/**
 * 统计大纲规模，用于覆盖度展示。
 * @param {string} subject 学科键。
 * @returns {{modules: number, chapters: number}} 规模。
 */
export function syllabusSize(subject) {
  const modules = SYLLABUS[subject] ?? []
  return { modules: modules.length, chapters: modules.reduce((a, m) => a + m.chapters.length, 0) }
}
